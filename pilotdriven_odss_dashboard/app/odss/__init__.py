def _visual_paragraph_escape(value: str) -> str:
    """Escape source text while preserving Flight Briefing-controlled bold tags.

    The visual report uses ``<b>`` only for labels generated by the renderer.
    Every other angle bracket and ampersand from source material remains
    escaped. Unicode punctuation is normalised for reliable PDF rendering.
    """
    text = str(value).replace("…", "...").replace("→", "->")
    escaped = _xml_escape(text)
    return escaped.replace("&lt;b&gt;", "<b>").replace("&lt;/b&gt;", "</b>")


